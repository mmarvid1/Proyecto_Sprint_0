#ifndef LED_H_INCLUIDO
#define LED_H_INCLUIDO

// ===========================================================================
//  DISEÑO LÓGICO  --  LED.h
// ===========================================================================
//
//   tiempo: Z --> esperar()
//
//
//                 --------- LED ------------------
//                 |
//                 |
//                 |
//                 |
//                 |
//                 | numeroLED: Z
//                 | encendido: B
//                 |
//                 |
//   numero: Z --> LED() -->
//                 |
//                 |
//                 encender() -->
//                 |
//                 |
//                 apagar() -->
//                 |
//                 |
//                 alterar() -->
//                 |
//                 |
//   tiempo: Z --> brillar() -->
//                 |
//                 -------------------------------------
//
//
// ===========================================================================


// ----------------------------------------------------------
//   tiempo: Z --> esperar()
// ----------------------------------------------------------
void esperar (long tiempo) {
  delay (tiempo);
}

// ----------------------------------------------------------
// ----------------------------------------------------------
class LED {
private:
  int numeroLED;
  bool encendido;
public:

  // .........................................................
  //   numero: Z  --> LED() -->
  // .........................................................
  LED (int numero) : numeroLED (numero), encendido(false)
  {
	pinMode(numeroLED, OUTPUT);   // Configura el pin como salida y luego deja el LED apagado.
	apagar();
  }

  // .........................................................
  //   encender() -->
  // .........................................................
  void encender () {
	digitalWrite(numeroLED, HIGH); 
	encendido = true;
  }

  // .........................................................
  //   apagar() -->
  // .........................................................
  void apagar () {
	  digitalWrite(numeroLED, LOW);
	  encendido = false;
  }

  // .........................................................
  //   alterar() -->         
  // .........................................................
  void alternar () {
	if (encendido) {
	  apagar();
	} else {
	  encender ();
	}
  }

  // .........................................................
  //   tiempo: Z  --> brillar() -->
  // .........................................................
  void brillar (long tiempo) {
	encender ();
	esperar(tiempo); 
	apagar ();
  }
};

#endif